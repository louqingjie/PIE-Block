/// 生成 `staff_fixture.h` 的完整文本。
String buildStaffFixtureHeader(List<StaffFixtureScenario> scenarios) {
  // 注：本文件会被 gcc/SDCC 编译，注释保持 ASCII，避免跨平台编码问题。
  final buffer = StringBuffer()
    ..writeln(
      '/* Host-comparison fixtures (generated by Pie-Block; do not edit).',
    )
    ..writeln(' *')
    ..writeln(' * generate: dart run tool/emit_staff_fixtures.dart')
    ..writeln(' * verify:   dart run tool/emit_staff_fixtures.dart --check')
    ..writeln(' *')
    ..writeln(' * Each scenario\'s tables are emitted by pieblock_core')
    ..writeln(
      ' * (emitStaffFirmwareTables); golden/<scenario>_<frame:03d>.bin holds',
    )
    ..writeln(
      ' * 1024-byte SSD1306 page-format frames rendered by the Dart renderer,',
    )
    ..writeln(
      ' * which shares the integer layout with firmware StaffRender.c. */',
    )
    ..writeln('#ifndef STAFF_FIXTURE_H')
    ..writeln('#define STAFF_FIXTURE_H')
    ..writeln()
    ..writeln('#include "StaffRender.h"')
    ..writeln()
    ..writeln('#define STAFF_FIXTURE_SCENARIO_COUNT ${scenarios.length}')
    ..writeln();
  for (final scenario in scenarios) {
    buffer.writeln(
      '/* ---- scenario ${scenario.name}: key ${keyNameForFifths(scenario.keyFifths)}'
      ' (${scenario.song.keyCount} accidentals), '
      '${scenario.frameCount} frames ---- */',
    );
    buffer.write(
      emitStaffFirmwareTables(
        scenario.song,
        prefix: scenario.prefix,
        includeComment: false,
      ),
    );
    buffer.writeln();
  }
  buffer
    ..writeln('typedef struct')
    ..writeln('{')
    ..writeln('    const char *name;')
    ..writeln('    const StaffSong *song;')
    ..writeln('} StaffFixtureScenario;')
    ..writeln()
    ..writeln(
      'static const StaffFixtureScenario '
      'staffFixtureScenarios[STAFF_FIXTURE_SCENARIO_COUNT] =',
    )
    ..writeln('{');
  for (var i = 0; i < scenarios.length; i++) {
    final scenario = scenarios[i];
    final comma = i == scenarios.length - 1 ? '' : ',';
    buffer.writeln('    {"${scenario.name}", &${scenario.prefix}Song}$comma');
  }
  buffer
    ..writeln('};')
    ..writeln()
    ..writeln('#endif /* STAFF_FIXTURE_H */');
  return buffer.toString();
}

