/// 向上找到仓库根（含 pubspec.yaml 与 packages/pieblock_core）。
Directory repoRootDirectory() {
  var directory = Directory.current.absolute;
  while (true) {
    final hasPubspec = File('${directory.path}/pubspec.yaml').existsSync();
    final hasCore = Directory('${directory.path}/packages/pieblock_core')
        .existsSync();
    if (hasPubspec && hasCore) return directory;
    final parent = directory.parent;
    if (parent.path == directory.path) {
      throw StateError('找不到仓库根目录（从 ${Directory.current.path} 向上查找）');
    }
    directory = parent;
  }
}

/// fixture 根目录路径（默认仓库内路径；测试可传入临时目录）。
String staffFixtureRootPath({Directory? repoRoot, String? override}) {
  if (override != null) return override;
  final root = repoRoot ?? repoRootDirectory();
  return '${root.path}/$staffFixtureRelativeDir';
}

Directory staffFixtureGoldenDirectory(String fixtureRootPath) =>
    Directory('$fixtureRootPath/$staffFixtureGoldenDirName');

/// 写入/校验差异。
class StaffFixtureDrift {
  const StaffFixtureDrift(this.path, this.reason);

  final String path;
  final String reason;

  @override
  String toString() => '$path: $reason';
}

class StaffFixtureWriteResult {
  const StaffFixtureWriteResult({
    required this.scenarioCount,
    required this.frameCount,
    required this.removedStale,
  });

  final int scenarioCount;
  final int frameCount;
  final int removedStale;
}

/// 写入 fixture（header + golden 帧），并删除 golden 目录里多余的旧帧。
Future<StaffFixtureWriteResult> writeStaffFixtures(
  StaffFixtureBundle bundle, {
  String? fixtureRootPath,
}) async {
  final rootPath = fixtureRootPath ?? staffFixtureRootPath();
  final directory = Directory(rootPath);
  await directory.create(recursive: true);
  final goldenDirectory = staffFixtureGoldenDirectory(rootPath);
  await goldenDirectory.create(recursive: true);

  await File('$rootPath/$staffFixtureHeaderName')
      .writeAsString(bundle.header, flush: true);

  final expected = <String, StaffFixtureFrame>{
    for (final frame in bundle.frames) frame.fileName: frame,
  };
  for (final frame in bundle.frames) {
    await File('${goldenDirectory.path}/${frame.fileName}')
        .writeAsBytes(frame.bytes, flush: true);
  }

  var removedStale = 0;
  for (final entity in goldenDirectory.listSync()) {
    if (entity is! File) continue;
    final name = entity.uri.pathSegments.last;
    if (!name.endsWith('.bin')) continue;
    if (expected.containsKey(name)) continue;
    await entity.delete();
    removedStale++;
  }

  return StaffFixtureWriteResult(
    scenarioCount: bundle.scenarioCount,
    frameCount: bundle.frameCount,
    removedStale: removedStale,
  );
}

/// 重新计算 fixture 并与已提交文件比较；返回空列表表示完全一致。
Future<List<StaffFixtureDrift>> verifyStaffFixtures(
  StaffFixtureBundle bundle, {
  String? fixtureRootPath,
}) async {
  final rootPath = fixtureRootPath ?? staffFixtureRootPath();
  final drifts = <StaffFixtureDrift>[];

  final headerFile = File('$rootPath/$staffFixtureHeaderName');
  if (!headerFile.existsSync()) {
    drifts.add(StaffFixtureDrift(headerFile.path, '文件缺失（请重新生成 fixture）'));
  } else {
    final actual = await headerFile.readAsString();
    if (actual != bundle.header) {
      drifts.add(StaffFixtureDrift(headerFile.path, '内容与生成逻辑不一致'));
    }
  }

  final goldenDirectory = staffFixtureGoldenDirectory(rootPath);
  if (!goldenDirectory.existsSync()) {
    drifts.add(StaffFixtureDrift(goldenDirectory.path, '目录缺失（请重新生成 fixture）'));
    return drifts;
  }

  for (final frame in bundle.frames) {
    final file = File('${goldenDirectory.path}/${frame.fileName}');
    if (!file.existsSync()) {
      drifts.add(StaffFixtureDrift(file.path, '文件缺失（请重新生成 fixture）'));
      continue;
    }
    final actual = await file.readAsBytes();
    final difference = _firstDifference(actual, frame.bytes);
    if (difference != null) {
      drifts.add(StaffFixtureDrift(file.path, difference));
    }
  }

  final expectedNames = <String>{
    for (final frame in bundle.frames) frame.fileName,
  };
  for (final entity in goldenDirectory.listSync()) {
    if (entity is! File) continue;
    final name = entity.uri.pathSegments.last;
    if (!name.endsWith('.bin')) continue;
    if (expectedNames.contains(name)) continue;
    drifts.add(StaffFixtureDrift(entity.path, '多余文件（不在当前场景/帧数内，请重新生成）'));
  }

  return drifts;
}

String? _firstDifference(List<int> actual, List<int> expected) {
  if (actual.length != expected.length) {
    return '长度不一致：已提交 ${actual.length} 字节，生成 ${expected.length} 字节';
  }
  for (var i = 0; i < expected.length; i++) {
    if (actual[i] != expected[i]) {
      return '字节不一致：第 $i 字节 已提交 0x'
          '${actual[i].toRadixString(16).padLeft(2, '0')}'
          '，生成 0x${expected[i].toRadixString(16).padLeft(2, '0')}';
    }
  }
  return null;
}
