// 主机对拍 fixture 的生成逻辑（可 import 库）。
//
// 交付物（仓库内提交）：
//   stc32g_sdcc/tests/staff/fixtures/staff_fixture.h
//   stc32g_sdcc/tests/staff/fixtures/golden/<scenario>_<frame:03d>.bin
//
// `staff_fixture.h` 用 pieblock_core 的 emitStaffFirmwareTables 发射 6 个场景的
// C 数据表（含字形点阵、事件 SoA 表、调号步数），再给出 scenario 表；
// `golden/*.bin` 是 Dart 渲染器（与固件 StaffRender.c 同一套整数版面）输出的
// 1024 字节 SSD1306 页格式帧。主机 harness 编译该头并逐字节比较。
//
// 同一份逻辑供 CLI（tool/emit_staff_fixtures.dart）与根目录测试
// （test/staff_fixture_test.dart）共用，防止 fixture 与渲染器漂移。

import 'dart:io';
import 'dart:typed_data';

import 'package:pieblock_core/pieblock_core.dart';

import 'staff_render.dart';

/// fixture 目录（相对仓库根）。
const String staffFixtureRelativeDir = 'stc32g_sdcc/tests/staff/fixtures';
const String staffFixtureHeaderName = 'staff_fixture.h';
const String staffFixtureGoldenDirName = 'golden';

/// 一个 fixture 场景：名字 + C 前缀 + 配置 + 同源渲染器。
class StaffFixtureScenario {
  StaffFixtureScenario._({
    required this.name,
    required this.prefix,
    required this.config,
    required this.renderer,
  });

  factory StaffFixtureScenario({
    required String name,
    required String prefix,
    required MusicConfig config,
    RenderOptions options = const RenderOptions(),
  }) => StaffFixtureScenario._(
    name: name,
    prefix: prefix,
    config: config,
    renderer: StaffRenderer(config: config, options: options),
  );

  /// 场景名（写入 C 头与 golden 文件名，如 `twinkle`）。
  final String name;

  /// C 表前缀（如 `fixtureTwinkle` → `fixtureTwinkleSong`）。
  final String prefix;

  final MusicConfig config;
  final StaffRenderer renderer;

  StaffSongData get song => renderer.song;

  /// 帧数 = 事件数（每个音符/休止符一帧，与固件播放循环一致）。
  int get frameCount => song.events.length;

  int get keyFifths => song.keyFifths;
}

/// 一帧 golden 数据。
class StaffFixtureFrame {
  const StaffFixtureFrame({
    required this.scenario,
    required this.index,
    required this.bytes,
  });

  final String scenario;
  final int index;
  final Uint8List bytes;

  String get fileName => '${scenario}_${index.toString().padLeft(3, '0')}.bin';
}

/// 一次完整生成的产物（C 头文本 + 所有 golden 帧），供写入/校验/测试共用。
class StaffFixtureBundle {
  StaffFixtureBundle._({
    required this.scenarios,
    required this.frames,
    required this.header,
  });

  factory StaffFixtureBundle.generate() {
    final scenarios = buildStaffFixtureScenarios();
    final frames = <StaffFixtureFrame>[];
    for (final scenario in scenarios) {
      for (var index = 0; index < scenario.frameCount; index++) {
        final bitmap = scenario.renderer.renderFrame(index);
        frames.add(
          StaffFixtureFrame(
            scenario: scenario.name,
            index: index,
            bytes: Uint8List.fromList(bitmap.bytes),
          ),
        );
      }
    }
    return StaffFixtureBundle._(
      scenarios: scenarios,
      frames: List<StaffFixtureFrame>.unmodifiable(frames),
      header: buildStaffFixtureHeader(scenarios),
    );
  }

  final List<StaffFixtureScenario> scenarios;
  final List<StaffFixtureFrame> frames;
  final String header;

  int get scenarioCount => scenarios.length;
  int get frameCount => frames.length;
}

/// 6 个对拍场景（名字与 golden 文件名前缀一致）。
///
/// 覆盖：C 大调旋律、F 大调降号拼写、自动谱号切换、临时记号/还原号、
/// 各种休止符、C# 调 7 个升号 + 同小节还原号。
List<StaffFixtureScenario> buildStaffFixtureScenarios() =>
