/*************  功能说明    **************

重写printf调用的putchar函数，重定向到串口输出，可用于调试打印信息.

******************************************/

#include "FreeRTOS.h"

/* --stack-auto 下所有函数都按可重入约定编译，无需 Keil 的 reentrant 关键字。 */
extern void UartPutc(unsigned char dat);

/* SDCC 的 stdio.h 声明 int putchar(int)，这里按该原型重定向到串口。 */
int putchar(int c)
{
	UartPutc((unsigned char)c);
	return c;
}
